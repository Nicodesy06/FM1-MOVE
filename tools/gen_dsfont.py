# FM1 Move design-system fonts: rasterise Inter (SIL OFL 1.1, assets/fonts/inter) into 4-bit anti-aliased
# glyph subsets for the 240 x 240 screen (firmware/src/ds/ds_font.c draws them).
#
#   tools/gen_dsfont.py OUT.h [--preview PNG]
#
# Each font keeps only the characters its role needs (the 60 px numerals: digits and a few signs), with tight
# bounding boxes. Pixels are run-length coded: one byte = (run - 1) << 4 | alpha (0..15), runs of 1..16 pixels,
# row-major over the glyph box. Digits are tabular (OpenType tnum) so changing values never shift.
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = __file__.rsplit("/", 2)[0]
INTER = ROOT + "/assets/fonts/inter/"

CAPS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
DIGITS = "0123456789"
SIGNS = " .,:;-+/%#&()'!?<>=*_[]"

# name, file, px, tracking (px added to every advance), characters
FONTS = [
    ("DS_F12", "Inter-Bold.otf", 12, 0, CAPS + DIGITS + SIGNS),          # labels: caps (tracked when drawn)
    ("DS_F16", "Inter-SemiBold.otf", 16, 0, CAPS + DIGITS + SIGNS),      # values, list items
    ("DS_F22", "Inter-Bold.otf", 22, 0, CAPS + DIGITS + SIGNS),          # names, headings
    ("DS_F36", "InterDisplay-Bold.otf", 36, 0, CAPS + DIGITS + SIGNS),   # the touched value (overlay)
    ("DS_F64", "InterDisplay-Bold.otf", 64, -1, DIGITS + " .-+%:/"),     # hero numerals
]


def rle(px):
    out = bytearray()
    i = 0
    while i < len(px):
        v, n = px[i], 1
        while i + n < len(px) and px[i + n] == v and n < 16:
            n += 1
        out.append((n - 1) << 4 | v)
        i += n
    return out


def build(name, fname, px, track, chars):
    f = ImageFont.truetype(INTER + fname, px)
    asc, desc = f.getmetrics()
    feat = ["tnum"]
    glyphs, data = [], bytearray()
    chars = "".join(sorted(set(chars), key=chars.index))
    for ch in chars:
        adv = int(round(f.getlength(ch, features=feat))) + track
        W, H = px * 3, asc + desc + 8
        im = Image.new("L", (W, H), 0)
        ImageDraw.Draw(im).text((px, asc + 4), ch, font=f, fill=255, anchor="ls", features=feat)
        bb = im.getbbox()
        if not bb:
            glyphs.append((ch, len(data), 0, 0, 0, 0, adv))
            continue
        x0, y0, x1, y1 = bb
        crop = im.crop(bb)
        vals = [(a * 15 + 127) // 255 for a in (crop.get_flattened_data() if hasattr(crop, 'get_flattened_data') else crop.getdata())]
        off = len(data)
        data += rle(vals)
        glyphs.append((ch, off, x1 - x0, y1 - y0, x0 - px, y0 - 4, adv))
    cap = asc - f.getbbox("H", anchor="ls")[1] if False else -f.getbbox("H", anchor="ls")[1]
    return dict(name=name, h=asc + desc, base=asc, cap=cap, glyphs=glyphs, data=data, px=px, file=fname)


def emit(fonts, out):
    w = []
    w.append("/* generated by tools/gen_dsfont.py from Inter (SIL OFL 1.1, assets/fonts/inter/OFL.txt): do not edit */")
    total = 0
    for F in fonts:
        n = F["name"]
        m = [0xFF] * 96
        for i, g in enumerate(F["glyphs"]):
            m[ord(g[0]) - 32] = i
        w.append(f"/* {n}: {F['file']} {F['px']} px, {len(F['glyphs'])} glyphs, {len(F['data'])} B */")
        w.append(f"static const uint8_t {n}_MAP[96] = {{{','.join(str(v) for v in m)}}};")
        w.append(f"static const ds_glyph_t {n}_G[{len(F['glyphs'])}] = {{")
        for g in F["glyphs"]:
            w.append(f"    {{{g[1]}u, {g[2]}, {g[3]}, {g[4]}, {g[5]}, {g[6]}}},   /* {g[0]!r} */")
        w.append("};")
        d = F["data"]
        w.append(f"static const uint8_t {n}_D[{len(d)}] = {{")
        for i in range(0, len(d), 24):
            w.append("    " + ",".join(str(b) for b in d[i:i + 24]) + ",")
        w.append("};")
        w.append(f"static const ds_font_t {n} = {{{F['h']}, {F['base']}, {F['cap']}, {n}_MAP, {n}_G, {n}_D}};")
        total += len(d) + 96 + 8 * len(F["glyphs"])
    w.append(f"#define DS_FONT_BYTES {total}u")
    open(out, "w").write("\n".join(w) + "\n")
    return total


def preview(fonts, path):
    """the fonts decoded back from their RLE data, as the firmware sees them (a check of the encoder)"""
    H = sum(F["h"] + 10 for F in fonts) + 10
    im = Image.new("RGB", (720, H), (0, 0, 0))
    y = 5
    for F in fonts:
        x = 5
        for (ch, off, gw, gh, gx, gy, adv) in F["glyphs"]:
            vals, i = [], off
            while len(vals) < gw * gh:
                b = F["data"][i]
                vals += [b & 15] * ((b >> 4) + 1)
                i += 1
            for k, v in enumerate(vals[:gw * gh]):
                if v:
                    c = v * 17
                    px, py = x + gx + k % gw, y + gy + k // gw
                    if px < 720:
                        im.putpixel((px, py), (c, c, c))
            x += adv
            if x > 690:
                break
        y += F["h"] + 10
    im.save(path)


if __name__ == "__main__":
    fonts = [build(*a) for a in FONTS]
    total = emit(fonts, sys.argv[1])
    for F in fonts:
        print(f"{F['name']}: {F['px']} px {F['file']}, h {F['h']} cap {F['cap']}, {len(F['glyphs'])} glyphs, "
              f"{len(F['data'])} B")
    print(f"design-system fonts: {total} B")
    if "--preview" in sys.argv:
        preview(fonts, sys.argv[sys.argv.index("--preview") + 1])
